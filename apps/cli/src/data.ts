// File access for the CLI and the tests: the repository's data/ folder. Core never reads files; this module does.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import {
  type AttributeRegistry,
  AttributeRegistrySchema,
  citedText,
  type DeviceIr,
  DeviceIrSchema,
  type Example,
  ExamplesFileSchema,
  type NavigatorModel,
  type Obligation,
  ObligationsFileSchema,
  type Outline,
  OutlineSchema,
  type SectionLookup,
  type SourceMeta,
  SourceMetaSchema,
  type SourceSection,
  type Standard,
  StandardsFileSchema,
} from "@mrn/core";

export const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "../../..");
export const DATA_DIR = join(REPO_ROOT, "data");
export const SOURCES_DIR = join(DATA_DIR, "sources");

/** `data/sources/<id>/sections.json`: the outline's sections cut from text.txt (generated by `pnpm mrn sections`). */
export interface SectionsFile {
  source: string;
  textSha256: string;
  sections: SourceSection[];
}

export const sha256OfBytes = (bytes: Buffer | string) => createHash("sha256").update(bytes).digest("hex");

export const sourceDir = (id: string) => join(SOURCES_DIR, id);

/** Ids of the source folders (those with a meta.json). */
export function sourceIds(): string[] {
  if (!existsSync(SOURCES_DIR)) return [];
  return readdirSync(SOURCES_DIR)
    .filter((d) => existsSync(join(SOURCES_DIR, d, "meta.json")))
    .sort();
}

export function readJson(path: string): unknown {
  return JSON.parse(readFileSync(path, "utf8"));
}

/** Writes JSON; files outside data/sources are then formatted by Biome so `pnpm verify` stays green. */
export function writeJson(path: string, value: unknown): void {
  writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`);
  if (!relative(SOURCES_DIR, path).startsWith("..")) return;
  execFileSync(join(REPO_ROOT, "node_modules/.bin/biome"), ["format", "--write", path], { stdio: "ignore" });
}

export function readMeta(id: string): SourceMeta {
  return SourceMetaSchema.parse(readJson(join(sourceDir(id), "meta.json")));
}

export function originalPath(meta: Pick<SourceMeta, "id" | "format">): string {
  return join(sourceDir(meta.id), `original.${meta.format}`);
}

export function readTextLines(id: string): string[] {
  const text = readFileSync(join(sourceDir(id), "text.txt"), "utf8");
  return text.endsWith("\n") ? text.slice(0, -1).split("\n") : text.split("\n");
}

export function readOutline(id: string): Outline {
  return OutlineSchema.parse(readJson(join(sourceDir(id), "outline.json")));
}

export function readSections(id: string): SectionsFile {
  return readJson(join(sourceDir(id), "sections.json")) as SectionsFile;
}

/** Looks sections up across all sources, from their sections.json (normalised text computed once). */
export function sectionLookup(): SectionLookup {
  const cache = new Map<string, { sha256: string; text: string }>();
  for (const id of sourceIds()) {
    if (!existsSync(join(sourceDir(id), "sections.json"))) continue;
    for (const s of readSections(id).sections) cache.set(`${id}/${s.id}`, { sha256: s.sha256, text: citedText(s.raw) });
  }
  return (source, section) => cache.get(`${source}/${section}`);
}

/** Every JSON file under data/ except the sources (rules, attributes, obligations, examples, …). */
export function dataJsonFiles(dir = DATA_DIR): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (path === SOURCES_DIR) continue;
    if (statSync(path).isDirectory()) out.push(...dataJsonFiles(path));
    else if (name.endsWith(".json")) out.push(path);
  }
  return out;
}

export const repoPath = (path: string) => relative(REPO_ROOT, path);

export const RULES_DIR = join(DATA_DIR, "rules");
export const EXAMPLES_DIR = join(DATA_DIR, "examples");

export function readRegistry(): AttributeRegistry {
  return AttributeRegistrySchema.parse(readJson(join(DATA_DIR, "attributes.json")));
}

const jsonFilesIn = (dir: string) =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => f.endsWith(".json"))
        .sort()
        .map((f) => join(dir, f))
    : [];

/** The rule files as parsed JSON (unvalidated: validateRules reports problems). */
export function readRuleFiles(): { path: string; json: unknown }[] {
  return jsonFilesIn(RULES_DIR).map((path) => ({ path, json: readJson(path) }));
}

/** The rules, parsed (throws on a schema error; run validateRules for a full report). */
export function readRules(): DeviceIr[] {
  return readRuleFiles().map(({ json }) => DeviceIrSchema.parse(json));
}

export function readExamples(): Example[] {
  return jsonFilesIn(EXAMPLES_DIR).flatMap((path) => ExamplesFileSchema.parse(readJson(path)).examples);
}

export const OBLIGATIONS_DIR = join(DATA_DIR, "obligations");

export function readObligations(): Obligation[] {
  return jsonFilesIn(OBLIGATIONS_DIR).flatMap((path) => ObligationsFileSchema.parse(readJson(path)).obligations);
}

export function readStandards(): Standard[] {
  return StandardsFileSchema.parse(readJson(join(DATA_DIR, "standards.json"))).standards;
}

/** Everything the navigator needs, from data/. */
export function readModel(): NavigatorModel {
  return { registry: readRegistry(), rules: readRules(), obligations: readObligations(), standards: readStandards() };
}
